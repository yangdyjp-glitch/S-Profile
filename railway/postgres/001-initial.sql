CREATE TABLE "user" (
  id text PRIMARY KEY, name text NOT NULL, email text NOT NULL UNIQUE,
  email_verified integer NOT NULL DEFAULT 0, image text,
  created_at bigint NOT NULL DEFAULT (extract(epoch FROM now()) * 1000)::bigint,
  updated_at bigint NOT NULL DEFAULT (extract(epoch FROM now()) * 1000)::bigint,
  username text UNIQUE, display_username text, role text, banned integer DEFAULT 0,
  ban_reason text, ban_expires bigint
);
CREATE TABLE account (
  id text PRIMARY KEY, account_id text NOT NULL, provider_id text NOT NULL,
  user_id text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  access_token text, refresh_token text, id_token text, access_token_expires_at bigint,
  refresh_token_expires_at bigint, scope text, password text,
  created_at bigint NOT NULL DEFAULT (extract(epoch FROM now()) * 1000)::bigint,
  updated_at bigint NOT NULL
);
CREATE INDEX account_user_idx ON account(user_id);
CREATE TABLE session (
  id text PRIMARY KEY, expires_at bigint NOT NULL, token text NOT NULL UNIQUE,
  created_at bigint NOT NULL DEFAULT (extract(epoch FROM now()) * 1000)::bigint,
  updated_at bigint NOT NULL, ip_address text, user_agent text,
  user_id text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE, impersonated_by text
);
CREATE INDEX session_user_idx ON session(user_id);
CREATE TABLE verification (
  id text PRIMARY KEY, identifier text NOT NULL, value text NOT NULL, expires_at bigint NOT NULL,
  created_at bigint NOT NULL DEFAULT (extract(epoch FROM now()) * 1000)::bigint,
  updated_at bigint NOT NULL DEFAULT (extract(epoch FROM now()) * 1000)::bigint
);
CREATE INDEX verification_identifier_idx ON verification(identifier);
CREATE TABLE rate_limit (
  id text PRIMARY KEY, key text NOT NULL UNIQUE, count integer NOT NULL, last_request bigint NOT NULL
);
CREATE TABLE students (
  id text PRIMARY KEY, data text NOT NULL, version integer NOT NULL, updated_at text NOT NULL,
  identity text NOT NULL UNIQUE
);
CREATE TABLE catalogs (
  id text PRIMARY KEY, data text NOT NULL, version integer NOT NULL, updated_at text NOT NULL,
  kind text NOT NULL, name_key text NOT NULL, UNIQUE(kind, name_key)
);
CREATE TABLE services (
  id text PRIMARY KEY, data text NOT NULL, version integer NOT NULL, updated_at text NOT NULL,
  student_id text NOT NULL REFERENCES students(id)
);
CREATE INDEX services_student ON services(student_id);
CREATE TABLE applications (
  id text PRIMARY KEY, data text NOT NULL, version integer NOT NULL, updated_at text NOT NULL,
  service_id text NOT NULL REFERENCES services(id)
);
CREATE INDEX applications_service ON applications(service_id);
CREATE TABLE entries (
  id text PRIMARY KEY, data text NOT NULL, version integer NOT NULL, updated_at text NOT NULL,
  student_id text NOT NULL REFERENCES students(id)
);
CREATE INDEX entries_student ON entries(student_id);
CREATE TABLE guards (ok integer NOT NULL CONSTRAINT version_guard CHECK (ok = 1));
CREATE TABLE imports (
  id text PRIMARY KEY, name text NOT NULL, actor text NOT NULL, at text NOT NULL,
  state text NOT NULL, metadata text NOT NULL, object_key text NOT NULL
);
CREATE TABLE sources (
  id text PRIMARY KEY, batch_id text NOT NULL REFERENCES imports(id), sheet text NOT NULL,
  "row" integer NOT NULL, phase text NOT NULL, name text NOT NULL, identity text NOT NULL,
  raw text NOT NULL, proposal text NOT NULL, issues text NOT NULL, state text NOT NULL,
  student_id text, service_id text, reviewer text, reviewed_at text, resolution text
);
CREATE INDEX source_batch ON sources(batch_id, state, sheet, "row");
CREATE INDEX source_identity ON sources(batch_id, identity);
CREATE TABLE mutations (
  id text PRIMARY KEY, actor_id text NOT NULL, fingerprint text NOT NULL, result text NOT NULL
);
CREATE TABLE revisions (
  seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity text NOT NULL,
  entity_id text NOT NULL, student_id text NOT NULL, service_id text NOT NULL,
  version integer NOT NULL, action text NOT NULL, actor text NOT NULL, actor_id text NOT NULL,
  at text NOT NULL, before text, after text NOT NULL, UNIQUE(entity,entity_id,version)
);
CREATE INDEX history_student ON revisions(student_id, seq);
CREATE INDEX history_service ON revisions(service_id, seq);
CREATE TABLE setup_tickets (digest text PRIMARY KEY, expires bigint NOT NULL);
